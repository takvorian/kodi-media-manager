    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(512) NOT NULL,
    overview           TEXT,
    tmdb_collection_id VARCHAR(16),
    CONSTRAINT uk_movie_set_name UNIQUE (name)
);


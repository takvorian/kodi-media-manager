CREATE TABLE tv_show (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id           BIGINT        NOT NULL,
    directory_path      VARCHAR(1024) NOT NULL,
    directory_path_hash CHAR(64)      NOT NULL,
    title               VARCHAR(512)  NOT NULL,
    original_title      VARCHAR(512),
    sort_title          VARCHAR(512),
    release_year        INTEGER,
    premiered           DATE,
    plot                TEXT,
    runtime_minutes     INTEGER,
    mpaa                VARCHAR(64),
    status              VARCHAR(64),
    tvdb_id             VARCHAR(16),
    tmdb_id             VARCHAR(16),
    imdb_id             VARCHAR(16),
    user_rating         INTEGER,
    added_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    nfo_modified_at     TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_tv_show_directory_path_hash UNIQUE (directory_path_hash),
    CONSTRAINT fk_tv_show_source FOREIGN KEY (source_id) REFERENCES media_source (id) ON DELETE CASCADE
);
CREATE INDEX ix_tv_show_source ON tv_show (source_id);
CREATE INDEX ix_tv_show_title ON tv_show (title);

CREATE TABLE tv_show_genre (
    tv_show_id  BIGINT       NOT NULL,
    genre_order INTEGER      NOT NULL,
    genre       VARCHAR(128) NOT NULL,
    CONSTRAINT pk_tv_show_genre PRIMARY KEY (tv_show_id, genre_order),
    CONSTRAINT fk_tv_show_genre_show FOREIGN KEY (tv_show_id) REFERENCES tv_show (id) ON DELETE CASCADE
);

CREATE TABLE tv_show_studio (
    tv_show_id   BIGINT       NOT NULL,
    studio_order INTEGER      NOT NULL,
    studio       VARCHAR(255) NOT NULL,
    CONSTRAINT pk_tv_show_studio PRIMARY KEY (tv_show_id, studio_order),
    CONSTRAINT fk_tv_show_studio_show FOREIGN KEY (tv_show_id) REFERENCES tv_show (id) ON DELETE CASCADE
);

CREATE TABLE tv_show_tag (
    tv_show_id BIGINT       NOT NULL,
    tag_order  INTEGER      NOT NULL,
    tag        VARCHAR(255) NOT NULL,
    CONSTRAINT pk_tv_show_tag PRIMARY KEY (tv_show_id, tag_order),
    CONSTRAINT fk_tv_show_tag_show FOREIGN KEY (tv_show_id) REFERENCES tv_show (id) ON DELETE CASCADE
);

CREATE TABLE tv_show_actor (
    tv_show_id  BIGINT        NOT NULL,
    actor_order INTEGER       NOT NULL,
    name        VARCHAR(512)  NOT NULL,
    role        VARCHAR(512),
    thumb       VARCHAR(1024),
    CONSTRAINT pk_tv_show_actor PRIMARY KEY (tv_show_id, actor_order),
    CONSTRAINT fk_tv_show_actor_show FOREIGN KEY (tv_show_id) REFERENCES tv_show (id) ON DELETE CASCADE
);

CREATE TABLE tv_show_rating (
    tv_show_id     BIGINT           NOT NULL,
    rating_order   INTEGER          NOT NULL,
    source         VARCHAR(64)      NOT NULL,
    rating_value   DOUBLE PRECISION NOT NULL,
    max_value      INTEGER,
    votes          INTEGER,
    default_rating BOOLEAN          NOT NULL,
    CONSTRAINT pk_tv_show_rating PRIMARY KEY (tv_show_id, rating_order),
    CONSTRAINT fk_tv_show_rating_show FOREIGN KEY (tv_show_id) REFERENCES tv_show (id) ON DELETE CASCADE
);

CREATE TABLE tv_season (
    tv_show_id    BIGINT       NOT NULL,
    season_number INTEGER      NOT NULL,
    title         VARCHAR(512),
    CONSTRAINT pk_tv_season PRIMARY KEY (tv_show_id, season_number),
    CONSTRAINT fk_tv_season_show FOREIGN KEY (tv_show_id) REFERENCES tv_show (id) ON DELETE CASCADE
);

CREATE TABLE episode (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tv_show_id       BIGINT        NOT NULL,
    file_path        VARCHAR(1024) NOT NULL,
    file_path_hash   CHAR(64)      NOT NULL,
    season_number    INTEGER       NOT NULL,
    episode_number   INTEGER       NOT NULL,
    title            VARCHAR(512)  NOT NULL,
    original_title   VARCHAR(512),
    plot             TEXT,
    aired            DATE,
    runtime_minutes  INTEGER,
    tvdb_id          VARCHAR(16),
    tmdb_id          VARCHAR(16),
    imdb_id          VARCHAR(16),
    user_rating      INTEGER,
    play_count       INTEGER,
    last_played_at   TIMESTAMP(6) WITH TIME ZONE,
    added_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    nfo_modified_at  TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_episode_file_number UNIQUE (file_path_hash, season_number, episode_number),
    CONSTRAINT fk_episode_show FOREIGN KEY (tv_show_id) REFERENCES tv_show (id) ON DELETE CASCADE
);
CREATE INDEX ix_episode_show ON episode (tv_show_id, season_number, episode_number);

CREATE TABLE episode_credit (
    episode_id   BIGINT        NOT NULL,
    credit_order INTEGER       NOT NULL,
    credit_type  VARCHAR(16)   NOT NULL,
    name         VARCHAR(512)  NOT NULL,
    role         VARCHAR(512),
    thumb        VARCHAR(1024),
    CONSTRAINT pk_episode_credit PRIMARY KEY (episode_id, credit_order),
    CONSTRAINT fk_episode_credit_episode FOREIGN KEY (episode_id) REFERENCES episode (id) ON DELETE CASCADE
);

CREATE TABLE episode_rating (
    episode_id     BIGINT           NOT NULL,
    rating_order   INTEGER          NOT NULL,
    source         VARCHAR(64)      NOT NULL,
    rating_value   DOUBLE PRECISION NOT NULL,
    max_value      INTEGER,
    votes          INTEGER,
    default_rating BOOLEAN          NOT NULL,
    CONSTRAINT pk_episode_rating PRIMARY KEY (episode_id, rating_order),
    CONSTRAINT fk_episode_rating_episode FOREIGN KEY (episode_id) REFERENCES episode (id) ON DELETE CASCADE
);

ALTER TABLE media_source ADD COLUMN last_scanned_at TIMESTAMP(6) WITH TIME ZONE;

CREATE TABLE movie (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id      BIGINT        NOT NULL,
    file_path      VARCHAR(1024) NOT NULL,
    file_path_hash CHAR(64)      NOT NULL,
    title          VARCHAR(512)  NOT NULL,
    release_year   INTEGER,
    disc_format    VARCHAR(16)   NOT NULL,
    part_count     INTEGER       NOT NULL,
    added_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_movie_file_path_hash UNIQUE (file_path_hash),
    CONSTRAINT fk_movie_source FOREIGN KEY (source_id) REFERENCES media_source (id) ON DELETE CASCADE
);

CREATE INDEX ix_movie_source ON movie (source_id);
CREATE INDEX ix_movie_title ON movie (title);
